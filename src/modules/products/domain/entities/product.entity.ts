import type { ProductProps } from '../types/product-domain.types.js';

export class ProductEntity {
  private constructor(private readonly props: ProductProps) {}

  static create(
    props: Omit<ProductProps, 'id' | 'createdAt' | 'updatedAt'>,
  ): ProductEntity {
    const now = new Date();
    const productRequestProps: ProductProps = {
      ...props,
      id: 0, // Assuming the ID will be generated by the database
      createdAt: now,
      updatedAt: now,
    };
    return new ProductEntity(productRequestProps);
  }
  static reconstitute(props: ProductProps): ProductEntity {
    return new ProductEntity(props);
  }

  get id(): number {
    return this.props.id;
  }

  get sku(): string {
    return this.props.sku;
  }

  get name(): string {
    return this.props.name;
  }

  get description(): string {
    return this.props.description;
  }

  get unit(): string {
    return this.props.unit;
  }

  get minimumStock(): number {
    return this.props.minimumStock;
  }

  get isActive(): boolean {
    return this.props.isActive;
  }

  get categoryId(): number {
    return this.props.categoryId;
  }

  get createdAt(): Date {
    return this.props.createdAt;
  }

  get updatedAt(): Date {
    return this.props.updatedAt;
  }
}
