import type { UserProps, CreateUserProps } from '../types/user.types.js';

export class UserEntity {
  private constructor(private readonly props: UserProps) {}

  static create(props: CreateUserProps): UserEntity {
    const now = new Date();
    const userProps: UserProps = {
      ...props,
      id: 0, // Assuming the ID will be generated by the database
      createdAt: now,
      updatedAt: now,
    };
    return new UserEntity(userProps);
  }

  static reconstitute(props: UserProps): UserEntity {
    return new UserEntity(props);
  }

  get id(): number {
    return this.props.id;
  }

  get name(): string {
    return this.props.name.getValue();
  }

  get email(): string {
    return this.props.email.getValue();
  }

  get passwordHash(): string {
    return this.props.passwordHash;
  }

  get role(): number {
    return this.props.role.getValue();
  }

  get isActive(): number {
    return this.props.isActive.getValue();
  }

  get createdAt(): Date {
    return this.props.createdAt;
  }

  get updatedAt(): Date {
    return this.props.updatedAt;
  }
}
