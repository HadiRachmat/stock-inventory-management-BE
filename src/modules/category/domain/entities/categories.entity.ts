import type { CategoryProps } from '../types/categories-domain.types.js';
import { ProductEntity } from '../../../products/domain/entities/product.entity.js';

export class CategoryEntity {
  private constructor(private readonly props: CategoryProps) {}

  static create(
    props: Omit<CategoryEntity, 'id' | 'createdAt' | 'updatedAt'>,
  ): CategoryEntity {
    const now = new Date();
    const categoryRequestProps: CategoryProps = {
      ...props,
      id: 0, // Assuming the ID will be generated by the database
      createdAt: now,
      updatedAt: now,
    };
    return new CategoryEntity(categoryRequestProps);
  }

  static reconstitute(props: CategoryProps): CategoryEntity {
    return new CategoryEntity(props);
  }

  get id(): number {
    return this.props.id;
  }

  get name(): string {
    return this.props.name;
  }

  get description(): string {
    return this.props.description;
  }

  get product(): ProductEntity[] | undefined {
    return this.props.product;
  }
}
