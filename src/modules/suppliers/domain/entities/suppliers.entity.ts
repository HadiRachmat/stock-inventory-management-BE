import type {
  SupplierProps,
  CreateSupplierProps,
} from '../types/supplier-domain.types.js';

export class SupplierEntity {
  private constructor(private readonly props: SupplierProps) {}

  static create(props: CreateSupplierProps): SupplierEntity {
    const now = new Date();
    const supplierRequestProps: SupplierProps = {
      ...props,
      id: 0, // Assuming the ID will be generated by the database
      createdAt: now,
      updatedAt: now,
    };
    return new SupplierEntity(supplierRequestProps);
  }

  static reconstitute(props: SupplierProps): SupplierEntity {
    return new SupplierEntity(props);
  }

  get id(): number {
    return this.props.id;
  }

  get name(): string {
    return this.props.name.getValue();
  }

  get address(): string {
    return this.props.address.getValue();
  }

  get phone(): string {
    return this.props.phone.getValue();
  }

  get email(): string {
    return this.props.email.getValue();
  }

  get createdAt(): Date {
    return this.props.createdAt;
  }

  get updatedAt(): Date {
    return this.props.updatedAt;
  }
}
